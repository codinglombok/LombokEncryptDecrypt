// ── Ed25519 (RFC 8032) ────────────────────────────────────────────────

import { generateKeyPairSync, createPrivateKey, createPublicKey, sign } from 'node:crypto';

function makeEd25519Vec(id, seedHex, messageHex) {
  const oid = Buffer.from('302e020100300506032b6570042204', 'hex');
  const seed = fromHex(seedHex);
  const priv = createPrivateKey({ key: Buffer.concat([oid, seed, Buffer.from([0x20])].map((b,i) => i===0 ? b : i===1 ? b : b)), format: 'der', type: 'pkcs8' });
  const pub  = createPublicKey(priv);
  const pubDer = pub.export({ type: 'spki', format: 'der' });
  const pubKey = pubDer.slice(-32);
  const message = messageHex ? fromHex(messageHex) : Buffer.alloc(0);
  const sig = sign(null, message, priv);
  return { id, algorithm: 'Ed25519', source: 'RFC 8032', private_key: seedHex, public_key: hex(pubKey), message: messageHex, signature: hex(sig) };
}

