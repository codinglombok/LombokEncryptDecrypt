// ── AES-GCM vectors ─────────────────────────────────────────────────────

function aesGcmEncrypt(key, iv, plaintext, aad = Buffer.alloc(0)) {
  const cipher = createCipheriv(`aes-${key.length * 8}-gcm`, key, iv, { authTagLength: 16 });
  if (aad.length > 0) cipher.setAAD(aad);
  const ct  = Buffer.concat([cipher.update(plaintext), cipher.final()]);
  const tag = cipher.getAuthTag();
  return { ciphertext: hex(ct), tag: hex(tag) };
}

